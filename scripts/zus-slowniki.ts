/**
 * Generates src/shared/zus-slowniki.ts and src/shared/zus-zawody.ts from the dictionaries of the Płatnik update
 * package (pobierz.zus.pl/dystrybucja/slowniki/PakietyAktualizacjaP2_X_<n>.zip — the inner slU_*.xml.zip files
 * unpacked into one folder). Only the rows valid on `DZIEN` are kept. Public data, no personal data.
 *
 * Run: `npx tsx scripts/zus-slowniki.ts <folder with slU_*.xml> [pakiet]`
 */
import * as fs from 'fs';
import * as path from 'path';

const DZIEN = '2026-01-01';

const folder = process.argv[2];
const pakiet = process.argv[3] ?? '?';
if (!folder) {
  console.error('Usage: npx tsx scripts/zus-slowniki.ts <folder with slU_*.xml> [package number]');
  process.exit(1);
}

type Wiersz = Record<string, string>;

const ENCJE: Record<string, string> = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" };
const odkoduj = (s: string) => s.replace(/&(#\d+|[a-z]+);/gi, (all, e: string) => (e[0] === '#' ? String.fromCodePoint(Number(e.slice(1))) : (ENCJE[e] ?? all)));

/** The `<w k1=".." k2=".." />` rows of one dictionary, keyed by column name (k1 → its header name). */
function wczytaj(nazwa: string): Wiersz[] {
  const tekst = fs.readFileSync(path.join(folder, `${nazwa}.xml`), 'utf8').replace(/^﻿/, '');
  const naglowek = /<slp\s([^>]*)>/.exec(tekst);
  if (!naglowek) throw new Error(`${nazwa}: no <slp>`);
  const kolumny: Record<string, string> = {};
  for (const m of naglowek[1].matchAll(/(k\d+)="([^"]*)"/g)) kolumny[m[1]] = m[2];
  const out: Wiersz[] = [];
  for (const w of tekst.matchAll(/<w\s([^>]*?)\/>/g)) {
    const r: Wiersz = {};
    for (const a of w[1].matchAll(/(k\d+)="([^"]*)"/g)) r[kolumny[a[1]] ?? a[1]] = odkoduj(a[2]).replace(/\s+/g, ' ').trim();
    out.push(r);
  }
  return out;
}

const wazny = (od: string | undefined, doo: string | undefined) => (!od || od <= DZIEN) && (!doo || doo >= DZIEN);

/** Last row per code wins (the dictionaries list a code once per period). */
function poKodzie(rows: Wiersz[], kod: string, opis: string, od: string, doo: string): [string, string][] {
  const m = new Map<string, string>();
  for (const r of rows) if (wazny(r[od], r[doo]) && r[kod]) m.set(r[kod], r[opis]);
  return [...m.entries()].sort((a, b) => a[0].localeCompare(b[0]));
}

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lista = (nazwa: string, typ: string, pary: string[]) => `export const ${nazwa}: ${typ} = [\n${pary.map((p) => `  ${p},`).join('\n')}\n];\n`;

const tytuly = poKodzie(wczytaj('slU_TytUb'), 'STU_KOD_TYT_UBEZP', 'STU_OPIS', 'STU_OKRES_OD', 'STU_OKRES_DO');
const nfz = wczytaj('slU_KodOddzNFZ')
  .filter((r) => !r.KH_DTLIKW || r.KH_DTLIKW >= DZIEN)
  .map((r) => [r.KH_KD, r.KH_FIRMA] as [string, string])
  .sort((a, b) => a[0].localeCompare(b[0]));
const przyczyny = poKodzie(wczytaj('slU_KodPrzyWyrUb'), 'SZU_KODPRZYWYRZUB', 'SZU_OPIS', 'SZU_DATA_WAZN_OD', 'SZU_DATA_WAZN_DO');
const pokrewienstwo = poKodzie(wczytaj('slU_KodPokrew'), 'STP_KODPOKREW', 'STP_OPIS', 'STP_DATA_WAZN_OD', 'STP_DATA_WAZN_DO');
const wygasniecie = poKodzie(wczytaj('slU_KodWygas'), 'SKW_KOD', 'SKW_OPIS', 'SKW_DATA_OD', 'SKW_DATA_DO');
const podstawy = poKodzie(wczytaj('slU_PodstPrawWygas'), 'SPW_KOD', 'SPW_OPIS', 'SPW_DATA_OD', 'SPW_DATA_DO');
const swiadczenia = new Map<string, Wiersz>();
for (const r of wczytaj('slU_SwiadPrzerw')) if (wazny(r.DATA_WAZN_OD, r.DATA_WAZN_DO)) swiadczenia.set(r.KOD_SWIADPRZERW, r);

// The occupation dictionary is read by position: k3 = 6-digit code, k4 = 'Z' for an occupation (the other rows
// are groups), k5 = name, k6 / k7 = validity.
const zawodyTekst = fs.readFileSync(path.join(folder, 'slU_KodyZawodow.xml'), 'utf8');
const zawodyPary = new Map<string, string>();
for (const w of zawodyTekst.matchAll(/<w\s([^>]*?)\/>/g)) {
  const a: Record<string, string> = {};
  for (const m of w[1].matchAll(/(k\d+)="([^"]*)"/g)) a[m[1]] = odkoduj(m[2]).replace(/\s+/g, ' ').trim();
  if (a.k4 === 'Z' && /^\d{6}$/.test(a.k3 ?? '') && wazny(a.k6, a.k7)) zawodyPary.set(a.k3, a.k5);
}

const naglowek = (opis: string) => `/**
 * ${opis}
 * Generated by scripts/zus-slowniki.ts from the Płatnik update package ${pakiet} (rows valid on ${DZIEN}) —
 * do not edit by hand; run the script again on a newer package.
 */
`;

const slowniki =
  naglowek('Dictionaries of ZUS documents (Płatnik slU_*): insurance titles, NFZ branches, deregistration reasons, family ties, RSA benefit / break codes, the end of employment.') +
  '\n' +
  lista('ZUS_TYTULY', 'readonly (readonly [string, string])[]', tytuly.map(([k, v]) => `[${q(k)}, ${q(v)}]`)) +
  '\n' +
  lista('ZUS_NFZ', 'readonly (readonly [string, string])[]', nfz.map(([k, v]) => `[${q(k)}, ${q(v)}]`)) +
  '\n' +
  lista('ZUS_PRZYCZYNY_WYREJESTROWANIA', 'readonly (readonly [string, string])[]', przyczyny.map(([k, v]) => `[${q(k)}, ${q(v)}]`)) +
  '\n' +
  lista('ZUS_POKREWIENSTWO', 'readonly (readonly [string, string])[]', pokrewienstwo.map(([k, v]) => `[${q(k)}, ${q(v)}]`)) +
  '\n' +
  lista('ZUS_KODY_WYGASNIECIA', 'readonly (readonly [string, string])[]', wygasniecie.map(([k, v]) => `[${q(k)}, ${q(v)}]`)) +
  '\n' +
  lista('ZUS_PODSTAWY_WYGASNIECIA', 'readonly (readonly [string, string])[]', podstawy.map(([k, v]) => `[${q(k)}, ${q(v)}]`)) +
  '\n' +
  `/**
 * RSA codes: [code, description, amount, days]. \`kwota\` / \`dni\` as the dictionary marks them — 'Y' the
 * position is not filled, anything else ('M', 'S', 'W', 'DT', 'DS', …) means Płatnik asks for it.
 */
` +
  lista(
    'ZUS_SWIADCZENIA_PRZERWY',
    'readonly (readonly [string, string, string, string])[]',
    [...swiadczenia.values()]
      .sort((a, b) => a.KOD_SWIADPRZERW.localeCompare(b.KOD_SWIADPRZERW))
      .map((r) => `[${q(r.KOD_SWIADPRZERW)}, ${q(r.OPIS)}, ${q(r.CZY_KWOTA)}, ${q(r.CZY_DNIZASIL)}]`),
  );

const zawodyPlik =
  naglowek('Occupation codes (KZiS, slU_KodyZawodow) for ZUA block X / ZZA block V — a separate module, loaded only by the screens that pick one.') +
  '\n' +
  lista(
    'ZUS_ZAWODY',
    'readonly (readonly [string, string])[]',
    [...zawodyPary.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([k, v]) => `[${q(k)}, ${q(v)}]`),
  );

const korzen = path.join(__dirname, '..', 'src', 'shared');
fs.writeFileSync(path.join(korzen, 'zus-slowniki.ts'), slowniki);
fs.writeFileSync(path.join(korzen, 'zus-zawody.ts'), zawodyPlik);
console.log(
  `tytuły ${tytuly.length}, NFZ ${nfz.length}, przyczyny ${przyczyny.length}, pokrewieństwo ${pokrewienstwo.length}, ` +
    `wygaśnięcie ${wygasniecie.length}, podstawy ${podstawy.length}, RSA ${swiadczenia.size}, zawody ${zawodyPary.size}`,
);
