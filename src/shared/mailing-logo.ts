/**
 * INTER-EJ letterhead used by the Mailing module, embedded as base64.
 *
 * Inlined into the source rather than shipped as a file: `package.json`'s
 * electron-builder `files` list only packages `dist/**`, `config/**` and
 * `node_modules/**`, so a logo dropped in `resources/` would be missing from the
 * installed app — and a mailing whose logo silently disappears in the packaged
 * build is exactly the kind of bug nobody notices until a city unit gets it.
 *
 * ── Why there are two copies of the same artwork ──────────────────────────────
 * The only version of this logo published anywhere is a 293 × 117 PNG on
 * inter-ej.waw.pl (confirmed against their WordPress media library: every other
 * size it serves is smaller). Scaled up to letterhead size that bitmap is
 * visibly soft, and it prints worse still — a PDF at 300 DPI stretches it ~3×.
 *
 * So the artwork here is a vector trace of that PNG: the shapes are the
 * company's own outlines, lifted from the bitmap rather than redrawn in a
 * substitute font, and they stay sharp at any size or print resolution.
 *
 *   • SVG  — used by the PDF and the in-app previews, both rendered by Chromium.
 *            Vector all the way into the PDF, so printing is clean.
 *   • PNG  — used by the mail, at 879 × 351 (3× its 220 px display width) and
 *            palette-reduced to 64 colours. Mail clients do not render SVG, and
 *            a 3× raster is what keeps the logo crisp on high-DPI screens.
 *
 * If the company can supply the designer's original (SVG/AI/EPS, or simply a
 * large PNG), replace both constants — a first-hand asset always beats a trace.
 *
 * The lettering is a light off-white (their site puts it on a dark header), so
 * it must never be placed on a light background — `buildDocumentHtml` always
 * renders it on the dark band in `LOGO_BAND_COLOR`, taken from the same site.
 */

